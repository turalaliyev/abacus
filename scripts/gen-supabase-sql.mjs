/**
 * Generates supabase/004_content_refresh.sql from src/data/content.ts.
 *
 * The site's anon key is read-only by design (see abacus-admin/supabase/
 * 003_admin_rls.sql — writes require an authenticated session), so content
 * updates ship as SQL to paste into the Supabase SQL editor rather than as a
 * script that needs a service-role secret.
 *
 * Everything here is idempotent: re-running it is safe.
 *
 *   node scripts/gen-supabase-sql.mjs
 */

import { writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { faqItems, services, siteConfig, stats, whyUsItems } from '../src/data/content.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Dollar-quoting avoids escaping hell with apostrophes and HTML. */
let tagCounter = 0
function q(value) {
  if (value === null || value === undefined) return 'NULL'
  const text = String(value)
  let tag = `t${tagCounter++}`
  while (text.includes(`$${tag}$`)) tag = `t${tagCounter++}`
  return `$${tag}$${text}$${tag}$`
}

const lines = []
const w = (s = '') => lines.push(s)

w(`-- ===========================================================================`)
w(`-- 004_content_refresh.sql`)
w(`--`)
w(`-- Generated by scripts/gen-supabase-sql.mjs — do not edit by hand.`)
w(`-- Regenerate after changing src/data/content.ts.`)
w(`--`)
w(`-- Paste into the Supabase SQL editor and run. Safe to run more than once.`)
w(`--`)
w(`-- Only the Azerbaijani (az) values are written. The en/ru keys inside the`)
w(`-- *_i18n columns are preserved untouched, because the source text was taken`)
w(`-- verbatim from abacusaudit.az and machine-translating tax and legal wording`)
w(`-- is not safe to do unreviewed.`)
w(`-- ===========================================================================`)
w()
w('BEGIN;')
w()

/* ---------------------------------------------------------------- services */
w('-- ── services: short card summary column ───────────────────────────────────')
w('ALTER TABLE services ADD COLUMN IF NOT EXISTS summary text NOT NULL DEFAULT $$$$;')
w("ALTER TABLE services ADD COLUMN IF NOT EXISTS summary_i18n jsonb NOT NULL DEFAULT '{}'::jsonb;")
w()

w('-- ── services: align the personnel slug with its public URL ────────────────')
w('-- The site routes /xidmetler/kadr; the CMS row was still slugged hr-audit.')
w(`UPDATE services SET slug = 'kadr' WHERE slug = 'hr-audit';`)
w()

w('-- ── services: full copy imported from abacusaudit.az ──────────────────────')
for (const s of services) {
  w(`UPDATE services SET`)
  w(`  title         = ${q(s.title)},`)
  w(`  summary       = ${q(s.summary)},`)
  w(`  description   = ${q(s.description)},`)
  w(`  icon          = ${q(s.icon)},`)
  w(`  image_url     = ${q(`/services/${s.slug}.webp`)},`)
  w(`  title_i18n       = jsonb_set(coalesce(title_i18n, '{}'::jsonb),       '{az}', to_jsonb(${q(s.title)}::text)),`)
  w(`  summary_i18n     = jsonb_set(coalesce(summary_i18n, '{}'::jsonb),     '{az}', to_jsonb(${q(s.summary)}::text)),`)
  w(`  description_i18n = jsonb_set(coalesce(description_i18n, '{}'::jsonb), '{az}', to_jsonb(${q(s.description)}::text))`)
  w(`WHERE slug = ${q(s.slug)};`)
  w()
}

/* ------------------------------------------------------------- why_us_items */
w('-- ── why_us_items: the five real reasons from the live site ────────────────')
w('-- Replaces the four generic placeholders.')
w('DELETE FROM why_us_items;')
whyUsItems.forEach((item, i) => {
  w(`INSERT INTO why_us_items (title, description, sort_order, title_i18n, description_i18n) VALUES (`)
  w(`  ${q(item.title)}, ${q(item.description)}, ${i + 1},`)
  w(`  jsonb_build_object('az', ${q(item.title)}::text),`)
  w(`  jsonb_build_object('az', ${q(item.description)}::text)`)
  w(`);`)
})
w()

/* --------------------------------------------------------------------- stats */
w('-- ── stats ─────────────────────────────────────────────────────────────────')
w('-- NOTE: the old third stat read "3 Ofis". Only one office address is')
w('-- published on abacusaudit.az, so it is replaced with a verifiable figure.')
w('-- If three offices is correct, edit this block before running.')
w('DELETE FROM stats;')
stats.forEach((s, i) => {
  w(`INSERT INTO stats (value, suffix, label, sort_order, label_i18n) VALUES (`)
  w(`  ${s.value}, ${q(s.suffix)}, ${q(s.label)}, ${i + 1}, jsonb_build_object('az', ${q(s.label)}::text)`)
  w(`);`)
})
w()

/* ------------------------------------------------------------- site_settings */
w('-- ── site_settings: real contact details and social profiles ───────────────')
w('-- The previous rows held placeholders (https://facebook.com, a wrong')
w('-- WhatsApp number). These are the live values from abacusaudit.az.')
w('UPDATE site_settings SET')
w(`  phone         = ${q(siteConfig.phone)},`)
w(`  email         = ${q(siteConfig.email)},`)
w(`  address       = ${q(siteConfig.address.full)},`)
w(`  facebook_url  = ${q(siteConfig.social.facebook)},`)
w(`  instagram_url = ${q(siteConfig.social.instagram)},`)
w(`  linkedin_url  = ${q(siteConfig.social.linkedin)},`)
w(`  whatsapp_url  = ${q(siteConfig.social.whatsapp)}`)
w('WHERE id = 1;')
w()

/* ----------------------------------------------------------------------- faq */
w('-- ── faq_items: new table backing the homepage FAQ + FAQPage schema ────────')
w(`CREATE TABLE IF NOT EXISTS faq_items (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  question    text NOT NULL,
  answer      text NOT NULL,
  sort_order  int  NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT true,
  question_i18n jsonb NOT NULL DEFAULT '{}'::jsonb,
  answer_i18n   jsonb NOT NULL DEFAULT '{}'::jsonb
);`)
w()
w('ALTER TABLE faq_items ENABLE ROW LEVEL SECURITY;')
w(`DROP POLICY IF EXISTS "Public read faq_items" ON faq_items;`)
w(`CREATE POLICY "Public read faq_items" ON faq_items
  FOR SELECT TO public USING (is_published);`)
w(`DROP POLICY IF EXISTS "Admin all faq_items" ON faq_items;`)
w(`CREATE POLICY "Admin all faq_items" ON faq_items
  FOR ALL TO authenticated USING (true) WITH CHECK (true);`)
w()
w('DELETE FROM faq_items;')
faqItems.forEach((item, i) => {
  w(`INSERT INTO faq_items (question, answer, sort_order, question_i18n, answer_i18n) VALUES (`)
  w(`  ${q(item.question)}, ${q(item.answer)}, ${i + 1},`)
  w(`  jsonb_build_object('az', ${q(item.question)}::text),`)
  w(`  jsonb_build_object('az', ${q(item.answer)}::text)`)
  w(`);`)
})
w()

w('COMMIT;')
w()

const outPath = join(root, 'supabase/004_content_refresh.sql')
await mkdir(dirname(outPath), { recursive: true })
await writeFile(outPath, lines.join('\n'), 'utf8')

console.log(`Wrote supabase/004_content_refresh.sql`)
console.log(`  services      ${services.length}`)
console.log(`  why_us_items  ${whyUsItems.length}`)
console.log(`  stats         ${stats.length}`)
console.log(`  faq_items     ${faqItems.length}`)
